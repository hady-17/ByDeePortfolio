export const makeP3 = (lang: Lang) => (key: string, vars?: Record<string, string>) => {
  let s = p3[lang][key] ?? p3.en[key] ?? '';
  if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
};
